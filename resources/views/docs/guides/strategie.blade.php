<h2 class="chapter" id="ch5"><span class="chapter-num">Chapitre 5</span>Trois routines à adopter</h2>
<p class="chapter-lead">Le pilotage stratégique tient dans trois rythmes complémentaires.</p>

<h3>Chaque semaine — 15 minutes</h3>
<ul class="checklist">
    <li>Ouvrir le tableau de bord Stratégie.</li>
    <li>Lire les alertes (objectifs en retard, KPI en alerte, plans en retard).</li>
    <li>Actualiser les <strong>KPI hebdomadaires</strong> avec les dernières valeurs mesurées.</li>
    <li>Vérifier les actions du <strong>plan d'action</strong> qui devaient se terminer cette semaine.</li>
</ul>

<h3>Chaque mois — 1 heure (premier lundi)</h3>
<ul class="checklist">
    <li>Actualiser tous les <strong>KPI mensuels</strong>.</li>
    <li>Passer en revue les <strong>KPI critiques</strong> : quelle cause racine ? quelle action corrective ?</li>
    <li>Passer en revue les <strong>KPI au top</strong> : quelle bonne pratique généraliser ?</li>
    <li>Faire évoluer les <strong>plans d'action</strong> — clôturer les actions terminées, ajouter les nouvelles.</li>
</ul>

<h3>Chaque trimestre — 3 heures (fin de trimestre)</h3>
<ul class="checklist">
    <li>Lancer les <strong>évaluations trimestrielles</strong> de chaque objectif opérationnel.</li>
    <li>Consolider les <strong>évaluations croisées</strong> (chef ↔ collaborateur).</li>
    <li>Réviser les <strong>cibles KPI</strong> annuelles si l'environnement a changé (ajuster, ne pas laisser dériver).</li>
    <li>Préparer une <strong>revue COPIL</strong> pour les objectifs stratégiques — présenter le taux d'atteinte, les écarts, les décisions.</li>
</ul>

