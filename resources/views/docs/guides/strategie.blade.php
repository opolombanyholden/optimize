<h2 class="chapter" id="ch1"><span class="chapter-num">Chapitre 1</span>Avant de commencer</h2>
<p class="chapter-lead">Ce guide accompagne la <strong>direction générale</strong>, le <strong>contrôle de gestion</strong> et le <strong>responsable qualité</strong> dans le pilotage stratégique de l'organisation via OptimiZe. Il vous permet de traduire une vision en objectifs, en indicateurs mesurables, en plans d'action concrets, puis d'évaluer leur atteinte.</p>

<h3>Ce que vous allez apprendre</h3>
<p>Définir des <strong>objectifs stratégiques</strong> et les décliner en <strong>objectifs opérationnels</strong>, construire un <strong>tableau de KPI</strong> pertinent avec cible/actuelle/tendance/périodicité, structurer des <strong>plans d'action</strong> par objectif, animer les <strong>évaluations périodiques</strong> et boucler le cycle d'amélioration continue.</p>

<h3>Comment utiliser ce guide</h3>
<p>Quatre types d'encarts jalonnent le texte :</p>
<div class="callout callout-tip"><span class="callout-label">Astuce</span>Un raccourci ou une meilleure façon de faire.</div>
<div class="callout callout-warn"><span class="callout-label">Attention</span>Un point de vigilance.</div>
<div class="callout callout-info"><span class="callout-label">Le saviez-vous ?</span>Une info contextuelle.</div>
<div class="callout callout-ok"><span class="callout-label">Résultat attendu</span>Ce que vous devriez voir une fois l'action réalisée.</div>

<h3>Ce dont vous avez besoin</h3>
<ul class="checklist">
    <li>Vos identifiants OptimiZe.</li>
    <li>Rôle disposant au minimum de <em>read:objectif, read:kpi, read:evaluation, read:plan_action</em>.</li>
    <li>Rôle <strong>admin</strong>, <strong>super-admin</strong> ou permission <em>create:objectif/kpi/evaluation/plan_action</em> pour la saisie.</li>
</ul>

<div class="callout callout-info">
    <span class="callout-label">Le saviez-vous ?</span>
    Un bon système d'indicateurs suit la règle des <strong>« 10 KPI or les »</strong> : moins de 10 KPI critiques suivis <em>ensemble</em>, tous alignés sur les objectifs stratégiques. Plus d'indicateurs = perte de focus.
</div>

