<h2 class="chapter" id="ch3"><span class="chapter-num">Chapitre 3</span>Comprendre la hiérarchie stratégique</h2>
<p class="chapter-lead">Le module suit une hiérarchie inspirée du <strong>Balanced Scorecard</strong> et de la méthode <strong>OKR</strong>. Comprendre cette structure fait gagner du temps sur toute la configuration.</p>

<h3>La pyramide en 4 niveaux</h3>
<table class="data">
    <thead><tr><th>Niveau</th><th>Rôle</th><th>Exemple concret</th></tr></thead>
    <tbody>
        <tr><td><strong>Objectif stratégique</strong></td><td>Direction long terme (12-36 mois), fixé par la direction générale</td><td>« Devenir leader régional du secteur »</td></tr>
        <tr><td><strong>Objectif opérationnel</strong></td><td>Décline un objectif stratégique en résultats concrets (3-12 mois)</td><td>« Ouvrir 3 nouvelles agences en 2026 »</td></tr>
        <tr><td><strong>KPI</strong></td><td>Mesure quantifiée du niveau d'atteinte (avec cible)</td><td>« Nombre d'agences ouvertes / 3 »</td></tr>
        <tr><td><strong>Plan d'action</strong></td><td>Actions concrètes à mener pour atteindre l'objectif</td><td>« Sélectionner sites », « Recruter managers », « Formation équipes »</td></tr>
    </tbody>
</table>

<h3>Cascade : de la vision à l'action</h3>
<div class="flow">
    <div class="flow-step"><div class="flow-step-num">1</div><div class="flow-step-name">Objectif stratégique</div><div class="flow-step-who">Vision → intentions</div></div>
    <div class="flow-step"><div class="flow-step-num">2</div><div class="flow-step-name">Objectifs opérationnels</div><div class="flow-step-who">Déclinaison en résultats mesurables</div></div>
    <div class="flow-step"><div class="flow-step-num">3</div><div class="flow-step-name">KPI</div><div class="flow-step-who">Quantification de l'atteinte</div></div>
    <div class="flow-step"><div class="flow-step-num">4</div><div class="flow-step-name">Plans d'action</div><div class="flow-step-who">Exécution concrète</div></div>
    <div class="flow-step"><div class="flow-step-num">5</div><div class="flow-step-name">Évaluations</div><div class="flow-step-who">Bilan périodique + ajustement</div></div>
</div>

<h3>Portées et types d'objectif</h3>
<p>Chaque objectif a une <strong>portée</strong> qui indique son niveau organisationnel : <em>Globale</em> (toute l'organisation), <em>Direction</em> (une direction spécifique), <em>Service</em> (un service), <em>Équipe</em>, <em>Individuelle</em>. Le donut du dashboard visualise votre répartition — un bon équilibre est signe de déclinaison réussie.</p>

<div class="callout callout-info">
    <span class="callout-label">Le saviez-vous ?</span>
    Un objectif <strong>stratégique bien formulé</strong> respecte la règle <strong>SMART</strong> : <em>Spécifique, Mesurable, Atteignable, Réaliste, Temporel</em>. Sans ces 5 caractéristiques, il devient une intention floue impossible à évaluer.
</div>

<h3>Cycle d'évaluation</h3>
<p>Une évaluation clôture une période (trimestre, semestre, année) et pose un verdict sur l'atteinte des objectifs. Elle peut être :</p>
<ul class="checklist">
    <li><strong>Auto-évaluation</strong> — chaque responsable évalue ses propres objectifs</li>
    <li><strong>Évaluation croisée</strong> — le supérieur hiérarchique évalue les objectifs de son équipe</li>
    <li><strong>Évaluation formelle</strong> — comité (COPIL) statue sur les objectifs stratégiques</li>
</ul>

