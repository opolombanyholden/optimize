<h2 class="chapter" id="ch4"><span class="chapter-num">Chapitre 4</span>Vos tâches quotidiennes</h2>
<p class="chapter-lead">Sept workflows couvrent l'ensemble de votre usage.</p>

<h3>4.1 · Créer un objectif stratégique</h3>
<table class="steps">
    <tr><td class="step-num"><span>1</span></td><td class="step-body"><div class="step-title">Menu Objectifs stratégiques</div><p>Sidebar → accordéon Objectifs → <strong>Stratégiques</strong> → <span class="btn-ref">+ Nouvel objectif</span>.</p></td></tr>
    <tr><td class="step-num"><span>2</span></td><td class="step-body"><div class="step-title">Renseigner</div><p>Code (« OBJ-2026-001 »), titre (formulation SMART), description, portée (Globale par défaut pour un objectif stratégique), dates début/fin (typiquement 12-36 mois), responsable, service porteur, pondération (poids relatif).</p></td></tr>
    <tr><td class="step-num"><span>3</span></td><td class="step-body"><div class="step-title">Choisir un statut initial</div><p><em>Actif</em> par défaut. Autres valeurs : <em>Atteint</em>, <em>Abandonné</em>, <em>Suspendu</em>.</p></td></tr>
    <tr><td class="step-num"><span>4</span></td><td class="step-body"><div class="step-title">Enregistrer</div><p><span class="btn-ref">Créer</span>. L'objectif apparaît dans la liste. Vous pouvez maintenant lui rattacher des sous-objectifs, des KPI et des plans d'action.</p></td></tr>
</table>

<h3>4.2 · Décliner en objectifs opérationnels</h3>
<p>Un objectif stratégique doit se traduire en 2-5 objectifs opérationnels concrets. Sinon il reste une intention.</p>

<table class="steps">
    <tr><td class="step-num"><span>1</span></td><td class="step-body"><div class="step-title">Ouvrir l'objectif stratégique</div><p>Cliquez sur son titre dans la liste. Vous voyez la fiche complète.</p></td></tr>
    <tr><td class="step-num"><span>2</span></td><td class="step-body"><div class="step-title">Ajouter un sous-objectif</div><p>Section « Sous-objectifs » → <span class="btn-ref">+ Ajouter</span>. Renseignez comme pour un objectif normal, mais rattaché au parent (<code>parent_id</code>).</p></td></tr>
    <tr><td class="step-num"><span>3</span></td><td class="step-body"><div class="step-title">Répéter pour chaque axe</div><p>Un objectif stratégique « Devenir leader régional » peut se décliner en : « Ouvrir 3 agences » + « Recruter 15 commerciaux » + « Atteindre 5000 clients ». Chacun devient un sous-objectif indépendant.</p></td></tr>
</table>

<div class="callout callout-tip">
    <span class="callout-label">Astuce</span>
    L'avancement de l'objectif parent se calcule automatiquement à partir de la <strong>moyenne pondérée</strong> de ses sous-objectifs. Vous ne saisissez qu'au niveau opérationnel — la cascade fait le reste.
</div>

<h3>4.3 · Créer un KPI attaché à un objectif</h3>
<p>Un KPI quantifie l'atteinte d'un objectif. Sans lui, l'objectif reste subjectif.</p>

<table class="steps">
    <tr><td class="step-num"><span>1</span></td><td class="step-body"><div class="step-title">Menu Tableau de KPI</div><p>Sidebar → accordéon Indicateurs → <strong>Tableau de KPI</strong> → <span class="btn-ref">+ Nouveau KPI</span>.</p></td></tr>
    <tr><td class="step-num"><span>2</span></td><td class="step-body"><div class="step-title">Renseigner l'identité</div><p>Titre (« Nombre d'agences ouvertes »), description, objectif de rattachement (via référentiel), unité (« unités », « % », « K XAF », « jours »).</p></td></tr>
    <tr><td class="step-num"><span>3</span></td><td class="step-body"><div class="step-title">Cible et périodicité</div><p><strong>Valeur cible</strong> (« 3 » agences), <strong>périodicité</strong> (mensuelle, trimestrielle, annuelle) : à quelle fréquence vous relèverez la valeur.</p></td></tr>
    <tr><td class="step-num"><span>4</span></td><td class="step-body"><div class="step-title">Actualiser la valeur régulièrement</div><p>À chaque relève : mettre à jour <strong>Valeur actuelle</strong>. Le pourcentage d'atteinte se calcule (actuelle / cible × 100). La <strong>tendance</strong> (↑ ↓ →) évolue selon les 3 dernières valeurs.</p></td></tr>
</table>

<div class="callout callout-warn">
    <span class="callout-label">Attention</span>
    Un KPI sans <strong>valeur cible</strong> ne peut pas être noté « en alerte » ni « au top » — il apparaît juste comme une donnée brute. Toujours renseigner une cible ambitieuse mais atteignable.
</div>

<h3>4.4 · Construire un plan d'action</h3>
<p>Chaque objectif opérationnel doit être adossé à un plan d'action. Sans lui, l'objectif reste théorique.</p>

<table class="steps">
    <tr><td class="step-num"><span>1</span></td><td class="step-body"><div class="step-title">Menu Plans d'action</div><p>Sidebar → accordéon Objectifs → <strong>Plans d'action</strong> → <span class="btn-ref">+ Nouveau plan</span>.</p></td></tr>
    <tr><td class="step-num"><span>2</span></td><td class="step-body"><div class="step-title">Rattacher à l'objectif</div><p>Sélectionnez l'objectif concerné. Le plan devient une liste concrète d'actions pour atteindre cet objectif.</p></td></tr>
    <tr><td class="step-num"><span>3</span></td><td class="step-body"><div class="step-title">Ajouter les actions</div><p>Pour chaque action : libellé, responsable, date début/fin prévues, priorité, coût estimé, dépendances (si séquentielles).</p></td></tr>
    <tr><td class="step-num"><span>4</span></td><td class="step-body"><div class="step-title">Suivre l'exécution</div><p>Chaque action a un statut (À faire / En cours / Terminée / Bloquée). Actualisez au fil des semaines. L'avancement global du plan se calcule automatiquement.</p></td></tr>
</table>

<h3>4.5 · Lancer une évaluation</h3>
<p>Une évaluation formalise un bilan périodique. Elle produit un verdict et alimente le pilotage.</p>

<table class="steps">
    <tr><td class="step-num"><span>1</span></td><td class="step-body"><div class="step-title">Menu Évaluations</div><p>Sidebar → accordéon Évaluations → <strong>Toutes les évaluations</strong> → <span class="btn-ref">+ Nouvelle évaluation</span>.</p></td></tr>
    <tr><td class="step-num"><span>2</span></td><td class="step-body"><div class="step-title">Périmètre et période</div><p>Choisissez l'objectif (ou lot d'objectifs), le type (auto / croisée / formelle), la période évaluée (Q3 2026, S1, année N…), l'évaluateur, l'évalué.</p></td></tr>
    <tr><td class="step-num"><span>3</span></td><td class="step-body"><div class="step-title">Renseigner la grille</div><p>Note globale d'atteinte (%), points forts observés, écarts constatés, causes racines, décisions correctives.</p></td></tr>
    <tr><td class="step-num"><span>4</span></td><td class="step-body"><div class="step-title">Finaliser</div><p><span class="btn-ref">Finaliser</span> — l'évaluation passe en statut immuable. Elle apparaîtra dans l'historique de l'objectif et alimentera les cycles suivants.</p></td></tr>
</table>

<div class="callout callout-info">
    <span class="callout-label">Le saviez-vous ?</span>
    Les <strong>évaluations finalisées</strong> sont comptabilisées sur le KPI du dashboard « Évaluations finalisées ». Un taux &lt; 70 % en fin de période signale que votre organisation n'a pas bouclé son cycle — les enseignements ne pourront pas nourrir la période suivante.
</div>

<h3>4.6 · Interpréter le dashboard</h3>

<h4>Priority bar</h4>
<p>Réagissez d'abord aux alertes rouges (objectifs en retard, KPI en alerte) — ce sont les urgences stratégiques.</p>

<h4>Top objectifs stratégiques</h4>
<p>Les 8 objectifs stratégiques triés par progression. Chaque ligne a une <strong>barre colorée</strong> :</p>
<ul class="checklist">
    <li>🟢 vert (≥ 70 %) — objectif bien parti</li>
    <li>🟠 orange (40-69 %) — surveillance nécessaire</li>
    <li>🔴 rouge (&lt; 40 %) — intervention requise</li>
    <li>Badge « Retard » si la date de fin est dépassée sans atteinte</li>
</ul>

<h4>KPI critiques vs KPI au top</h4>
<p>Deux blocs symétriques :</p>
<ul class="checklist">
    <li><strong>Critiques</strong> — KPI &lt; 50 % de leur cible, triés par progression croissante. Où mettre l'énergie ?</li>
    <li><strong>Au top</strong> — KPI ≥ 90 %, triés par progression décroissante. Où célébrer et capitaliser ?</li>
</ul>

<h4>Répartitions donut / statut</h4>
<p>Le donut « par portée » vérifie que votre stratégie se décline aux bons niveaux. Le bar-chart « par statut » vous dit combien d'objectifs sont actifs vs atteints vs abandonnés — un ratio élevé d'abandons peut signaler une stratégie trop ambitieuse ou mal calibrée.</p>

<h3>4.7 · Ajuster en cours de cycle</h3>
<p>La stratégie n'est jamais figée. Modifier un objectif ou une cible KPI en cours de cycle est acceptable — à condition de tracer la décision.</p>

<table class="steps">
    <tr><td class="step-num"><span>1</span></td><td class="step-body"><div class="step-title">Ouvrir la fiche</div><p>Fiche objectif ou KPI → <span class="btn-ref">Modifier</span>. Une justification doit accompagner tout changement significatif (nouvelle cible, nouvelle date de fin).</p></td></tr>
    <tr><td class="step-num"><span>2</span></td><td class="step-body"><div class="step-title">Consigner dans la description</div><p>Ajouter en fin de description « Ajusté le {date} pour {motif} » — la traçabilité qualitative reste manuelle mais essentielle.</p></td></tr>
    <tr><td class="step-num"><span>3</span></td><td class="step-body"><div class="step-title">Communiquer</div><p>Prévenir les responsables et évaluateurs concernés — un ajustement non communiqué crée une dissonance en évaluation.</p></td></tr>
</table>

