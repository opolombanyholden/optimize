        </td>
    </tr>
</table>

<div class="callout callout-info">
    <span class="callout-label">Le saviez-vous ?</span>
    Chaque page wiki conserve un <strong>historique complet des modifications</strong>. Vous pouvez comparer deux versions et restaurer une version antérieure. Rien n'est jamais perdu.
</div>

