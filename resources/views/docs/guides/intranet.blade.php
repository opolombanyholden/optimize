<h2 class="chapter" id="ch4"><span class="chapter-num">Chapitre 4</span>Vos tâches quotidiennes</h2>
<p class="chapter-lead">Neuf workflows couvrent la quasi-totalité de votre usage quotidien de l'intranet.</p>

<h3>4.1 · Publier une annonce</h3>
<p>Pour les <strong>animateurs</strong> disposant de la permission <em>publish:annonce</em>.</p>

<table class="steps">
    <tr>
        <td class="step-num"><span>1</span></td>
        <td class="step-body">
            <div class="step-title">Menu Annonces</div>
            <p>Sidebar → Communication → <strong>Annonces</strong> → <span class="btn-ref">+ Nouvelle annonce</span>.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>2</span></td>
        <td class="step-body">
            <div class="step-title">Rédiger</div>
            <p>Titre (court et clair), contenu (éditeur riche), cible (public / privé / entités spécifiques), niveau (<em>info</em>, <em>importante</em>, <em>urgente</em>).</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>3</span></td>
        <td class="step-body">
            <div class="step-title">Publier</div>
            <p><span class="btn-ref">Publier</span> — l'annonce apparaît immédiatement sur le dashboard de tous les collaborateurs concernés. Une annonce <em>urgente</em> s'affiche avec un bandeau rouge en tête.</p>
        </td>
    </tr>
</table>

<div class="callout callout-warn">
    <span class="callout-label">Attention</span>
    Une annonce publiée est visible <strong>immédiatement</strong> de tous. Relisez-vous avant de cliquer « Publier ». Une correction ultérieure laissera une trace dans l'historique.
</div>

<h3>4.2 · Créer une actualité (news) avec image</h3>
<p>Pour publier un article long avec image de couverture, format enrichi.</p>

<table class="steps">
    <tr>
        <td class="step-num"><span>1</span></td>
        <td class="step-body">
            <div class="step-title">Nouvelle actualité</div>
            <p>Sidebar → Communication → <strong>Actualités</strong> → <span class="btn-ref">+ Nouvelle actualité</span>.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>2</span></td>
        <td class="step-body">
            <div class="step-title">Renseigner et illustrer</div>
            <p>Titre, chapeau (2-3 lignes qui donnent envie de cliquer), contenu (éditeur Quill avec titres, gras, listes, liens, images inline), <strong>image de couverture</strong> (recommandé — 1200×630 px).</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>3</span></td>
        <td class="step-body">
            <div class="step-title">Sauvegarder puis publier</div>
            <p><span class="btn-ref">Enregistrer</span> crée l'actualité en brouillon. <span class="btn-ref">Publier</span> la met en ligne.</p>
        </td>
    </tr>
</table>

<h3>4.3 · Consulter le calendrier et s'inscrire à un événement</h3>

<table class="steps">
    <tr>
        <td class="step-num"><span>1</span></td>
        <td class="step-body">
            <div class="step-title">Ouvrir le calendrier</div>
            <p>Sidebar → Agenda → <strong>Calendrier</strong>. Vue par mois par défaut. Bascule mois / semaine / jour en haut à droite.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>2</span></td>
        <td class="step-body">
            <div class="step-title">Ouvrir un événement</div>
            <p>Clic sur une pastille colorée du calendrier ou depuis la liste <strong>Événements</strong>.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>3</span></td>
        <td class="step-body">
            <div class="step-title">S'inscrire</div>
            <p>Bouton <span class="btn-ref">S'inscrire</span>. Vous apparaissez dans la liste des participants. L'organisateur voit votre inscription.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>4</span></td>
        <td class="step-body">
            <div class="step-title">Annuler si besoin</div>
            <p>Sur la même fiche, <span class="btn-ref btn-danger">Se désinscrire</span> avant la date de l'événement.</p>
        </td>
    </tr>
</table>

<h3>4.4 · Créer et suivre une opportunité CRM</h3>
<p>Une opportunité représente une affaire en cours avec un prospect ou un client.</p>

<table class="steps">
    <tr>
        <td class="step-num"><span>1</span></td>
        <td class="step-body">
            <div class="step-title">Nouvelle opportunité</div>
            <p>Sidebar → CRM → <strong>Opportunités</strong> → <span class="btn-ref">+ Nouvelle opportunité</span>.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>2</span></td>
        <td class="step-body">
            <div class="step-title">Rattacher au contact et à l'organisation</div>
            <p>Sélectionnez l'organisation (via annuaire CRM) et le contact principal. Créez-les depuis les menus <em>Contacts / Organisations</em> s'ils n'existent pas.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>3</span></td>
        <td class="step-body">
            <div class="step-title">Renseigner</div>
            <p>Objet, montant estimé, probabilité (0-100 %), date de clôture prévue, étape initiale (<em>Prospection</em>).</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>4</span></td>
        <td class="step-body">
            <div class="step-title">Faire évoluer</div>
            <p>Sur le <strong>Pipeline</strong> (Kanban), glissez la carte d'une colonne à l'autre au fur et à mesure : Prospection → Qualification → Proposition → Négociation → Gagnée / Perdue.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>5</span></td>
        <td class="step-body">
            <div class="step-title">Clôturer</div>
            <p>Étape finale : <span class="btn-ref">Marquer gagnée</span> ou <span class="btn-ref btn-danger">Marquer perdue</span> avec motif. L'opportunité passe en historique.</p>
        </td>
    </tr>
</table>

<h3>4.5 · Enregistrer et suivre un courrier</h3>
<p>Chaque courrier officiel (entrant ou sortant) doit être tracé pour la conformité.</p>

<table class="steps">
    <tr>
        <td class="step-num"><span>1</span></td>
        <td class="step-body">
            <div class="step-title">Nouveau courrier</div>
            <p>Sidebar → Documents &amp; GED → <strong>Courrier</strong> → <span class="btn-ref">+ Nouveau courrier</span>.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>2</span></td>
        <td class="step-body">
            <div class="step-title">Renseigner</div>
            <p>Sens (entrant / sortant), date, objet, expéditeur, destinataire, référence du document original, pièces jointes numérisées.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>3</span></td>
        <td class="step-body">
            <div class="step-title">Numéro chrono automatique</div>
            <p>Le système génère un numéro chronologique unique (ex : <code>CR-2026-0148</code>) qui devient la référence de traçabilité.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>4</span></td>
        <td class="step-body">
            <div class="step-title">Assigner et suivre</div>
            <p>Affectez le courrier à un service ou une personne pour traitement. Statut visible dans la liste : <em>Reçu / En cours / Traité / Archivé</em>.</p>
        </td>
    </tr>
</table>

<h3>4.6 · Déposer une ressource documentaire</h3>

<table class="steps">
    <tr>
        <td class="step-num"><span>1</span></td>
        <td class="step-body">
            <div class="step-title">Menu Ressources</div>
            <p>Sidebar → Documents &amp; GED → <strong>Ressources</strong> → <span class="btn-ref">+ Nouvelle ressource</span>.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>2</span></td>
        <td class="step-body">
            <div class="step-title">Uploader le fichier</div>
            <p>Glisser-déposer ou clic pour parcourir. Formats supportés : PDF, Word, Excel, PowerPoint, images.</p>
        </td>
    </tr>
    <tr>
        <td class="step-num"><span>3</span></td>
        <td class="step-body">
            <div class="step-title">Renseigner les métadonnées</div>
            <p>Titre, description, catégorie, tags, visibilité (public / privé / cibles). Ces informations permettront de retrouver le document via la recherche.</p>
        </td>
    </tr>
</table>

<div class="callout callout-tip">
    <span class="callout-label">Astuce</span>
    Utilisez des <strong>tags cohérents</strong> à travers l'organisation (« RH-Formation », « Compta-Procédure », « IT-Sécurité »). La recherche par tag est bien plus efficace que la recherche plein-texte.
</div>

<h3>4.7 · Créer et éditer une page wiki</h3>
<p>Le wiki est votre <strong>base de connaissances collaborative</strong>. Chacun peut contribuer.</p>

<table class="steps">
    <tr>
        <td class="step-num"><span>1</span></td>
