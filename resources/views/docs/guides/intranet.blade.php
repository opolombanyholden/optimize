<h2 class="chapter" id="ch1"><span class="chapter-num">Chapitre 1</span>Avant de commencer</h2>
<p class="chapter-lead">L'intranet est le portail collaboratif de votre organisation. C'est là que passe l'information officielle (annonces, actualités, événements) et que s'échange la connaissance (wiki, ressources, médiathèque). Ce guide s'adresse à <strong>tous les collaborateurs</strong>, avec des sections spécifiques pour les <strong>animateurs</strong> chargés de publier du contenu.</p>

<h3>Ce que vous allez apprendre</h3>
<p>Consulter les <strong>annonces</strong> et <strong>actualités</strong>, participer aux <strong>événements</strong>, gérer vos <strong>contacts et opportunités CRM</strong>, envoyer et suivre du <strong>courrier</strong> officiel, déposer et retrouver des <strong>ressources documentaires</strong>, contribuer au <strong>wiki</strong>, trouver n'importe qui dans l'<strong>annuaire</strong>.</p>

<h3>Comment utiliser ce guide</h3>
<p>Quatre types d'encarts jalonnent le texte :</p>

<div class="callout callout-tip">
    <span class="callout-label">Astuce</span>
    Un raccourci ou une meilleure façon de faire.
</div>
<div class="callout callout-warn">
    <span class="callout-label">Attention</span>
    Un point de vigilance — action difficilement réversible.
</div>
<div class="callout callout-info">
    <span class="callout-label">Le saviez-vous ?</span>
    Une info contextuelle pour comprendre le fonctionnement.
</div>
<div class="callout callout-ok">
    <span class="callout-label">Résultat attendu</span>
    Ce que vous devriez voir une fois l'action réalisée.
</div>

<h3>Ce dont vous avez besoin pour commencer</h3>
<ul class="checklist">
    <li>Vos identifiants OptimiZe (e-mail + mot de passe).</li>
    <li>Aucune permission particulière pour la <strong>consultation</strong> — tout collaborateur peut lire annonces, actualités, wiki, annuaire.</li>
    <li>Permissions <strong>publish:annonce</strong>, <strong>create:news</strong>, <strong>create:evenement</strong>, <strong>create:ressource</strong>, <strong>create:wiki</strong>, <strong>create:courrier</strong> pour les rôles <em>animateur intranet</em>.</li>
</ul>

<div class="callout callout-info">
    <span class="callout-label">Le saviez-vous ?</span>
    L'intranet est le premier écran que vous voyez après connexion. C'est <strong>votre page d'accueil</strong> — pensez à le consulter au moins une fois par jour pour rester au courant.
</div>

