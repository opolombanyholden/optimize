<h2 class="chapter" id="ch3"><span class="chapter-num">Chapitre 3</span>Découvrir les 6 sections de l'intranet</h2>
<p class="chapter-lead">La sidebar intranet regroupe 6 accordéons thématiques. Voici ce que chacun contient et à quoi il sert.</p>

<h3>3.1 · Communication</h3>
<p>Le canal officiel de l'organisation :</p>
<ul class="checklist">
    <li><strong>Annonces</strong> — messages courts et urgents (fermeture exceptionnelle, changement de règle). Peuvent être marquées « urgentes » pour un affichage en tête de dashboard.</li>
    <li><strong>Actualités (news)</strong> — articles longs avec image et texte enrichi (interviews, retour d'événements, communication institutionnelle).</li>
    <li><strong>Messagerie pro</strong> — <em>bientôt disponible</em>.</li>
</ul>

<h3>3.2 · Agenda</h3>
<ul class="checklist">
    <li><strong>Calendrier</strong> — vue mensuelle et hebdomadaire de tous les événements de l'organisation.</li>
    <li><strong>Événements</strong> — liste éditoriale : formations, réunions, célébrations. Chacun a une fiche avec description, date, lieu, participants inscrits.</li>
</ul>

<h3>3.3 · CRM (relations externes)</h3>
<ul class="checklist">
    <li><strong>Contacts</strong> — personnes externes (clients, prospects, partenaires).</li>
    <li><strong>Organisations</strong> — entreprises et institutions avec lesquelles vous travaillez.</li>
    <li><strong>Opportunités</strong> — affaires en cours de négociation, avec montant et probabilité.</li>
    <li><strong>Pipeline</strong> — vue Kanban des opportunités par étape (Prospection → Qualification → Proposition → Négociation → Gagnée/Perdue).</li>
</ul>

<h3>3.4 · Documents &amp; GED</h3>
<ul class="checklist">
    <li><strong>Courrier</strong> — traçabilité des courriers entrants et sortants (numéro chrono, expéditeur, objet, destinataire).</li>
    <li><strong>Ressources</strong> — bibliothèque de documents officiels (règlements, procédures, contrats types).</li>
    <li><strong>Médiathèque</strong> — bibliothèque d'images et vidéos (logos, photos d'événements, kits communication).</li>
    <li><strong>Archives</strong> — documents anciens conservés pour référence.</li>
    <li><strong>Templates</strong> — modèles de documents réutilisables (lettres, contrats, présentations).</li>
</ul>

<h3>3.5 · Connaissances</h3>
<ul class="checklist">
    <li><strong>Wiki</strong> — base de connaissances collaborative. Chacun peut créer une page, l'éditer, la lier à d'autres. Idéal pour les procédures, glossaires, FAQ internes.</li>
</ul>

<h3>3.6 · Annuaire</h3>
<ul class="checklist">
    <li><strong>Collaborateurs</strong> — trombinoscope avec fonction, département, contact.</li>
    <li><strong>Services</strong> — liste des services et de leurs responsables.</li>
    <li><strong>Équipes</strong> — équipes projets avec leurs membres et rôles.</li>
</ul>

<div class="callout callout-info">
    <span class="callout-label">Le saviez-vous ?</span>
    L'accordéon actif dans la sidebar s'ouvre automatiquement selon la page où vous êtes. Un seul accordéon ouvert à la fois — la navigation reste lisible même quand la sidebar est réduite.
</div>

