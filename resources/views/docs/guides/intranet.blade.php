<h2 class="chapter" id="ch5"><span class="chapter-num">Chapitre 5</span>Trois routines à adopter</h2>
<p class="chapter-lead">L'intranet devient un vrai outil de vie collective quand chacun a quelques réflexes.</p>

<h3>Chaque matin — 5 minutes</h3>
<ul class="checklist">
    <li>Ouvrir le dashboard Intranet.</li>
    <li>Lire les <strong>annonces urgentes</strong> (bandeau rouge).</li>
    <li>Consulter les <strong>événements du jour</strong> et de la semaine (calendrier).</li>
    <li>Traiter les <strong>courriers en attente</strong> qui vous ont été assignés.</li>
</ul>

<h3>Chaque semaine — 20 minutes (vendredi après-midi)</h3>
<ul class="checklist">
    <li>Lire les <strong>actualités de la semaine</strong> — restez au courant de la vie de l'organisation.</li>
    <li>Faire le point sur vos <strong>opportunités CRM</strong> ouvertes — mettre à jour l'étape et la probabilité.</li>
    <li>Vérifier vos <strong>inscriptions aux événements</strong> de la semaine suivante.</li>
    <li>Contribuer au <strong>wiki</strong> : documenter une astuce, une procédure, un apprentissage.</li>
</ul>

<h3>Chaque mois — 45 minutes (premier vendredi)</h3>
<ul class="checklist">
    <li>Faire le tour des <strong>ressources documentaires</strong> ajoutées durant le mois.</li>
    <li>Ranger vos anciens documents en <strong>archives</strong> — libère la vue courante.</li>
    <li>Actualiser votre <strong>profil</strong> : photo, présentation, coordonnées si changement.</li>
    <li>Consulter le <strong>pipeline CRM</strong> global — comprendre où en est l'activité commerciale.</li>
</ul>

<div class="callout callout-ok">
    <span class="callout-label">Résultat attendu</span>
    Après un trimestre d'application de ces trois routines, l'intranet cessera d'être une contrainte informatique pour devenir le vrai <strong>fil rouge de la vie de l'organisation</strong>. Vous connaîtrez mieux vos collègues, vous manquerez moins d'informations importantes, vous accéderez à vos documents plus vite.
</div>
